/**
 * CSV writers (stage 14). Two deliberately different formats:
 *
 * 1. VIEW exports (reports, product/inventory/order lists) — for reading in a spreadsheet, NOT for
 *    re-import. Every cell is quoted (RFC 4180: inner quotes doubled; commas, tabs and line breaks
 *    stay inside the quotes). Text cells that a spreadsheet could treat as a formula get a leading
 *    apostrophe ('): a cell whose first character, after any leading whitespace or control
 *    characters, is = + - @ or their full-width forms (＝ ＋ － ＠), or that starts with a tab or a
 *    carriage return. The stored value is unchanged; only the exported copy is prefixed. Numeric
 *    cells generated by the server (amounts, counts, deltas) are never prefixed.
 *
 * 2. CANONICAL import templates — machine format for the stage-13 importer. Values are written
 *    exactly (quoted, never prefixed), so a re-import reads the same text. Display-only fields that
 *    would be dangerous or ambiguous in a spreadsheet (formula-like text) are OMITTED (left empty)
 *    instead of being altered; authoritative fields (ids, versions) are always plain.
 *
 * Both start with a UTF-8 BOM and use CRLF.
 */

const FORMULA_LEAD = /^[\s\u0000-\u001f\u007f]*[=+\-@＝＋－＠]/;

/** True when a spreadsheet might interpret the text as a formula. */
export function isFormulaLike(text: string): boolean {
  return FORMULA_LEAD.test(text) || text.startsWith('\t') || text.startsWith('\r');
}

const quote = (s: string) => `"${s.replace(/"/g, '""')}"`;

export type Cell = { text: string } | { num: string } | null;
export const text = (s: string | null | undefined): Cell => (s === null || s === undefined ? null : { text: s });
export const num = (n: string | number | bigint): Cell => ({ num: String(n) });

/** View-export cell: formula-like text gets a leading apostrophe. */
export function viewCell(c: Cell): string {
  if (c === null) return '""';
  if ('num' in c) return quote(c.num);
  return quote(isFormulaLike(c.text) ? `'${c.text}` : c.text);
}

/** Canonical cell: exact text, quoted. */
export function canonicalCell(value: string): string {
  return quote(value);
}

export const BOM = '﻿';
export const CRLF = '\r\n';

/** Integer piastres (bigint or safe number) → "1234.50" (exact, no floating point). */
export function egp(cents: bigint | number): string {
  const v = BigInt(cents);
  const neg = v < 0n;
  const a = neg ? -v : v;
  return `${neg ? '-' : ''}${a / 100n}.${String(a % 100n).padStart(2, '0')}`;
}
