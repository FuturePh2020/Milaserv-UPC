import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { describe, it } from 'node:test';
import { parseCsv } from '../../src/server/import/csv.ts';
import { canonicalCell, egp, isFormulaLike, num, text, viewCell } from '../../src/server/reports/csv-out.ts';
import { dateRange, localDate, localDateTime, startOfLocalDay } from '../../src/server/reports/time.ts';
import { exactAll } from '../../src/server/services/reports.ts';

describe('spreadsheet-safe VIEW cells', () => {
  it('prefixes formula-like text, including whitespace/control/full-width bypasses; leaves other text unchanged', () => {
    const dangerous = ['=1+1', '+1', '-1', '@SUM(A1)', ' =1', '   +x', ' =1', '\u0001=1', '\n=1', '\t=1', '\tplain', '\rplain', '＝1', '＋1', '－1', '＠x', '=HYPERLINK("http://e","x")'];
    for (const d of dangerous) {
      assert.equal(isFormulaLike(d), true, JSON.stringify(d));
      assert.equal(viewCell(text(d)), `"'${d.replace(/"/g, '""')}"`, JSON.stringify(d));
    }
    for (const safe of ['شيكولاتة', 'a=b', 'x-1', 'email@x.com', '1-2', '(=)', "'already"]) {
      assert.equal(isFormulaLike(safe), false, safe);
      assert.equal(viewCell(text(safe)), `"${safe}"`);
    }
  });
  it('quotes delimiters, quotes and line breaks; numeric cells generated by the server are never prefixed', () => {
    assert.equal(viewCell(text('a,"b"\nc')), '"a,""b""\nc"');
    assert.equal(viewCell(num('-20')), '"-20"');
    assert.equal(viewCell(num(egp(-150n))), '"-1.50"');
    assert.equal(viewCell(null), '""');
  });
  it('canonical cells round-trip exactly through the import parser (no prefix, no loss)', () => {
    const values = ['=SUM(1,2)', 'شيكولاتة، "الأصلية"', 'سطر\nثانٍ', '000123', "'x", ' مسافة '];
    const line = values.map(canonicalCell).join(',');
    const r = parseCsv(new TextEncoder().encode(`${values.map((_, i) => `c${i}`).join(',')}\r\n${line}\r\n`));
    assert.ok(r.ok);
    if (r.ok) assert.deepEqual(r.table.records[0]!.cells, values);
  });
  it('money formatting is exact integer arithmetic', () => {
    assert.equal(egp(12550n), '125.50');
    assert.equal(egp(5), '0.05');
    assert.equal(egp(9_007_199_254_740_993n), '90071992547409.93', 'beyond Number precision');
  });
});

describe('report dates (Africa/Cairo)', () => {
  it('day boundaries: inclusive start, exclusive end, DST days', () => {
    assert.equal(startOfLocalDay('2026-01-15'), Date.parse('2026-01-14T22:00:00Z'));
    assert.equal(startOfLocalDay('2026-07-01'), Date.parse('2026-06-30T21:00:00Z'));
    // Spring forward at local midnight (last Friday of April 2026): the day starts at 01:00 local.
    assert.equal(startOfLocalDay('2026-04-24'), Date.parse('2026-04-23T22:00:00Z'));
    assert.equal(localDateTime(startOfLocalDay('2026-04-24')), '2026-04-24 01:00');
    assert.equal(localDate(startOfLocalDay('2026-04-24') - 1), '2026-04-23');
    const r = dateRange('2026-09-30', '2026-09-30');
    assert.equal(localDate(r.startMs), '2026-09-30');
    assert.equal(localDate(r.endMs - 1), '2026-09-30');
    assert.equal(localDate(r.endMs), '2026-10-01');
  });
  it('rejects invalid and reversed dates', () => {
    for (const [f, t] of [['2026-02-30', '2026-03-01'], ['2026-13-01', '2026-13-02'], ['26-01-01', '26-01-02'], ['2026-03-02', '2026-03-01']] as const) {
      assert.throws(() => dateRange(f, t));
    }
  });
});

describe('exact aggregation', () => {
  it('sums beyond 2^53 are exact (BigInt) and an int64 overflow is an explicit error, never a wrong total', () => {
    const db = new DatabaseSync(':memory:');
    db.exec('CREATE TABLE t (v INTEGER NOT NULL)');
    const ins = db.prepare('INSERT INTO t (v) VALUES (?)');
    ins.run(9_007_199_254_740_991n);
    ins.run(2n);
    assert.equal(exactAll(db, 'SELECT sum(v) AS s FROM t')[0]!.s, 9_007_199_254_740_993n);
    ins.run(9_223_372_036_854_775_000n);
    assert.throws(() => exactAll(db, 'SELECT sum(v) AS s FROM t'), (e: unknown) => (e as { code?: string }).code === 'AGGREGATE_OVERFLOW');
    db.close();
  });
});
